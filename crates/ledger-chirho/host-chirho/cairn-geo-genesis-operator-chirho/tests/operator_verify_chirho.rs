//! The read-only operator checks the genesis crate's own valid plan and dry-run packet. It refuses each
//! tampering and each wrong pin with a fixed identity. Its binary names its build, prints one JSON report
//! line on success, and on a refusal exits 1 without echoing the path it was given.
//!
//! The fixtures come from the genesis crate's ignored exporters (`export_operator_plan_fixtures_chirho`,
//! `export_operator_dry_run_fixture_chirho`). After a plan or packet schema change they break loudly,
//! and are regenerated by running those exporters.

use cairn_geo_genesis_operator_chirho::{
    verify_dry_run_report_chirho, verify_plan_report_chirho, OperatorRefusalChirho,
    DRY_RUN_REPORT_SCHEMA_CHIRHO, PLAN_REPORT_SCHEMA_CHIRHO, REFUSAL_SCHEMA_CHIRHO,
};
use std::path::{Path, PathBuf};
use std::process::Command;

fn fixture_path_chirho(name_chirho: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures-chirho")
        .join(name_chirho)
}

fn fixture_chirho(name_chirho: &str) -> Vec<u8> {
    std::fs::read(fixture_path_chirho(name_chirho)).expect("an exported operator fixture")
}

/// The two pinned public keys, as hex, and the plan digest the exporter recorded.
fn pins_chirho() -> (String, String, serde_json::Value) {
    let pins_chirho: serde_json::Value =
        serde_json::from_slice(&fixture_chirho("pins-chirho.json")).expect("pins JSON");
    (
        pins_chirho["plan_authority_key_chirho"]
            .as_str()
            .expect("a plan-authority hex key")
            .to_string(),
        pins_chirho["acceptance_authority_key_chirho"]
            .as_str()
            .expect("an acceptance-authority hex key")
            .to_string(),
        pins_chirho["plan_digest_chirho"].clone(),
    )
}

#[test]
fn the_pinned_reviewed_plan_verifies_and_reports_its_digest_chirho() {
    let (plan_key_chirho, acceptance_key_chirho, plan_digest_chirho) = pins_chirho();
    let report_chirho = verify_plan_report_chirho(
        &fixture_chirho("plan-chirho.json"),
        &fixture_chirho("ledger-plan-chirho.json"),
        &plan_key_chirho,
        &acceptance_key_chirho,
    )
    .expect("the exported plan verifies under its own pins");
    assert_eq!(report_chirho.schema_chirho, PLAN_REPORT_SCHEMA_CHIRHO);
    assert_eq!(report_chirho.plan_digest_chirho, plan_digest_chirho);
}

#[test]
fn a_plan_refuses_under_swapped_equal_or_malformed_pins_chirho() {
    let (plan_key_chirho, acceptance_key_chirho, _digest_chirho) = pins_chirho();
    let plan_chirho = fixture_chirho("plan-chirho.json");
    let ledger_chirho = fixture_chirho("ledger-plan-chirho.json");
    // Swapped: the plan is not authored under the key pinned as the plan authority.
    assert!(matches!(
        verify_plan_report_chirho(
            &plan_chirho,
            &ledger_chirho,
            &acceptance_key_chirho,
            &plan_key_chirho
        ),
        Err(OperatorRefusalChirho::GenesisChirho(_))
    ));
    // Equal: one key cannot hold both authorities.
    assert!(matches!(
        verify_plan_report_chirho(
            &plan_chirho,
            &ledger_chirho,
            &plan_key_chirho,
            &plan_key_chirho
        ),
        Err(OperatorRefusalChirho::GenesisChirho(_))
    ));
    // Malformed: not the hex form of a 32-byte key.
    assert!(matches!(
        verify_plan_report_chirho(
            &plan_chirho,
            &ledger_chirho,
            "not-hex-chirho",
            &acceptance_key_chirho
        ),
        Err(OperatorRefusalChirho::PinKeyInvalidChirho {
            pin_chirho: "plan-authority"
        })
    ));
}

#[test]
fn a_tampered_plan_or_a_non_canonical_ledger_plan_refuses_chirho() {
    let (plan_key_chirho, acceptance_key_chirho, _digest_chirho) = pins_chirho();
    let ledger_chirho = fixture_chirho("ledger-plan-chirho.json");
    let mut tampered_chirho = fixture_chirho("plan-chirho.json");
    let middle_chirho = tampered_chirho.len() / 2;
    tampered_chirho[middle_chirho] ^= 0x01;
    assert!(matches!(
        verify_plan_report_chirho(
            &tampered_chirho,
            &ledger_chirho,
            &plan_key_chirho,
            &acceptance_key_chirho
        ),
        Err(OperatorRefusalChirho::GenesisChirho(_))
    ));
    // The same ledger plan re-encoded with whitespace parses, but is not the reviewed bytes.
    let reencoded_chirho = serde_json::to_vec_pretty(
        &serde_json::from_slice::<serde_json::Value>(&ledger_chirho).expect("ledger plan JSON"),
    )
    .expect("re-encode");
    assert!(matches!(
        verify_plan_report_chirho(
            &fixture_chirho("plan-chirho.json"),
            &reencoded_chirho,
            &plan_key_chirho,
            &acceptance_key_chirho
        ),
        Err(OperatorRefusalChirho::LedgerPlanNotCanonicalChirho)
    ));
}

#[test]
fn the_dry_run_packet_verifies_and_a_tampered_one_refuses_chirho() {
    let packet_chirho = fixture_chirho("dry-run-packet-chirho.json");
    let report_chirho =
        verify_dry_run_report_chirho(&packet_chirho).expect("the exported packet verifies");
    assert_eq!(report_chirho.schema_chirho, DRY_RUN_REPORT_SCHEMA_CHIRHO);
    let mut tampered_chirho = packet_chirho.clone();
    let digit_chirho = tampered_chirho
        .iter()
        .position(u8::is_ascii_digit)
        .expect("the packet carries a count");
    tampered_chirho[digit_chirho] = if tampered_chirho[digit_chirho] == b'9' {
        b'8'
    } else {
        b'9'
    };
    assert!(matches!(
        verify_dry_run_report_chirho(&tampered_chirho),
        Err(OperatorRefusalChirho::GenesisChirho(_))
    ));
}

#[test]
fn the_binary_names_its_build_reports_one_line_and_never_echoes_a_path_chirho() {
    let binary_chirho = env!("CARGO_BIN_EXE_cairn-geo-genesis-operator-chirho");
    let version_chirho = Command::new(binary_chirho)
        .arg("--version")
        .output()
        .unwrap();
    assert!(version_chirho.status.success());
    assert!(String::from_utf8_lossy(&version_chirho.stdout)
        .starts_with("cairn-geo-genesis-operator-chirho "));

    let (plan_key_chirho, acceptance_key_chirho, _digest_chirho) = pins_chirho();
    let verified_chirho = Command::new(binary_chirho)
        .arg("verify-plan-chirho")
        .arg("--plan-chirho")
        .arg(fixture_path_chirho("plan-chirho.json"))
        .arg("--ledger-plan-chirho")
        .arg(fixture_path_chirho("ledger-plan-chirho.json"))
        .arg("--plan-authority-key-chirho")
        .arg(&plan_key_chirho)
        .arg("--acceptance-authority-key-chirho")
        .arg(&acceptance_key_chirho)
        .output()
        .unwrap();
    assert!(verified_chirho.status.success(), "{:?}", verified_chirho);
    let report_chirho: serde_json::Value =
        serde_json::from_slice(&verified_chirho.stdout).expect("one JSON report line");
    assert_eq!(report_chirho["schema_chirho"], PLAN_REPORT_SCHEMA_CHIRHO);

    let missing_chirho = std::env::temp_dir().join("cairn-geo-operator-no-such-plan-chirho.json");
    let refused_chirho = Command::new(binary_chirho)
        .arg("verify-dry-run-chirho")
        .arg("--packet-chirho")
        .arg(&missing_chirho)
        .output()
        .unwrap();
    assert_eq!(refused_chirho.status.code(), Some(1));
    let refusal_chirho: serde_json::Value =
        serde_json::from_slice(&refused_chirho.stderr).expect("one JSON refusal line");
    assert_eq!(refusal_chirho["schema_chirho"], REFUSAL_SCHEMA_CHIRHO);
    assert_eq!(
        refusal_chirho["refusal_chirho"],
        "InputUnreadableChirho:--packet-chirho"
    );
    assert!(
        !String::from_utf8_lossy(&refused_chirho.stderr).contains("no-such-plan"),
        "a refusal never echoes the path it was given"
    );

    // A path typed where a flag belongs is a usage error (exit 2) that never echoes the path.
    let stray_chirho = std::env::temp_dir().join("cairn-geo-operator-stray-path-chirho.json");
    let usage_chirho = Command::new(binary_chirho)
        .arg("verify-dry-run-chirho")
        .arg(&stray_chirho)
        .output()
        .unwrap();
    assert_eq!(usage_chirho.status.code(), Some(2));
    let usage_text_chirho = String::from_utf8_lossy(&usage_chirho.stderr);
    assert!(
        !usage_text_chirho.is_empty(),
        "a usage error explains itself"
    );
    assert!(
        !usage_text_chirho.contains("stray-path"),
        "a usage error never echoes the argument it could not place"
    );
}

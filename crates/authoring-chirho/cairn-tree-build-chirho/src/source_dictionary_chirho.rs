// For God so loved the world, that He gave His only begotten Son, that whoever believes in Him should not perish but have eternal life. - John 3:16

//! Generate typed Rust constants from reviewed app-local JSON dictionaries.
//! These are source artifacts for public/static copy, not a private-data escape hatch.

use crate::template_codegen_chirho::{
    checked_relative_output_path_chirho, checked_relative_source_path_chirho,
    rust_raw_string_literal_chirho, validate_function_name_chirho, validate_rust_type_path_chirho,
};
use std::path::{Path, PathBuf};

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SourceDictionarySpecChirho {
    pub dictionary_path_chirho: PathBuf,
    pub value_type_chirho: String,
    pub const_name_chirho: String,
    pub function_name_chirho: String,
}

pub fn generate_source_dictionary_source_chirho(
    app_root_chirho: &Path,
    spec_chirho: &SourceDictionarySpecChirho,
) -> Result<String, String> {
    let dictionary_path_chirho = checked_relative_source_path_chirho(
        app_root_chirho,
        &spec_chirho.dictionary_path_chirho,
        &["json"],
    )?;
    validate_rust_type_path_chirho(&spec_chirho.value_type_chirho)?;
    validate_const_name_chirho(&spec_chirho.const_name_chirho)?;
    validate_function_name_chirho(&spec_chirho.function_name_chirho)?;
    let source_chirho = std::fs::read_to_string(&dictionary_path_chirho)
        .map_err(|e_chirho| format!("read source dictionary: {e_chirho}"))?;
    let parsed_chirho: serde_json::Value = serde_json::from_str(&source_chirho)
        .map_err(|e_chirho| format!("source dictionary must be valid JSON: {e_chirho}"))?;
    if !parsed_chirho.is_object() {
        return Err("source dictionary JSON must be an object".to_string());
    }
    let source_literal_chirho = rust_raw_string_literal_chirho(&source_chirho);
    let try_function_chirho = format!("try_{}", spec_chirho.function_name_chirho);

    Ok(format!(
        concat!(
            "// For God so loved the world, that He gave His only Begotten Son, that whosoever believeth in Him should not perish, but have everlasting life. - John 3:16 (KJV)\n",
            "// Generated by tree-build-chirho from {dictionary_path_chirho}. Do not edit by hand.\n\n",
            "pub const {const_name_chirho}: &str = {source_literal_chirho};\n\n",
            "pub fn {try_function_chirho}() -> Result<{value_type_chirho}, serde_json::Error> {{\n",
            "    serde_json::from_str::<{value_type_chirho}>({const_name_chirho})\n",
            "}}\n\n",
            "pub fn {function_name_chirho}() -> {value_type_chirho} {{\n",
            "    {try_function_chirho}().expect(\"source dictionary JSON must match the generated value type\")\n",
            "}}\n",
        ),
        dictionary_path_chirho = spec_chirho.dictionary_path_chirho.display(),
        const_name_chirho = spec_chirho.const_name_chirho,
        source_literal_chirho = source_literal_chirho,
        try_function_chirho = try_function_chirho,
        value_type_chirho = spec_chirho.value_type_chirho,
        function_name_chirho = spec_chirho.function_name_chirho,
    ))
}

pub fn write_source_dictionary_source_chirho(
    app_root_chirho: &Path,
    spec_chirho: &SourceDictionarySpecChirho,
    output_path_chirho: &Path,
) -> Result<(), String> {
    let output_path_chirho =
        checked_relative_output_path_chirho(app_root_chirho, output_path_chirho, "rs")?;
    let generated_chirho = generate_source_dictionary_source_chirho(app_root_chirho, spec_chirho)?;
    if let Some(parent_chirho) = output_path_chirho.parent() {
        std::fs::create_dir_all(parent_chirho)
            .map_err(|e_chirho| format!("create generated dictionary dir: {e_chirho}"))?;
    }
    std::fs::write(&output_path_chirho, generated_chirho)
        .map_err(|e_chirho| format!("write generated dictionary: {e_chirho}"))
}

fn validate_const_name_chirho(name_chirho: &str) -> Result<(), String> {
    if !name_chirho.ends_with("_CHIRHO") {
        return Err("source dictionary const name must end with _CHIRHO".to_string());
    }
    let mut chars_chirho = name_chirho.chars();
    let Some(first_chirho) = chars_chirho.next() else {
        return Err("source dictionary const name must not be empty".to_string());
    };
    if !(first_chirho == '_' || first_chirho.is_ascii_uppercase()) {
        return Err(format!(
            "invalid source dictionary const name '{name_chirho}'"
        ));
    }
    if !chars_chirho.all(|ch_chirho| {
        ch_chirho == '_' || ch_chirho.is_ascii_uppercase() || ch_chirho.is_ascii_digit()
    }) {
        return Err(format!(
            "invalid source dictionary const name '{name_chirho}'"
        ));
    }
    Ok(())
}

#[cfg(test)]
mod tests_chirho {
    use super::*;

    fn temp_root_chirho(suffix_chirho: &str) -> PathBuf {
        let mut path_chirho = std::env::temp_dir();
        path_chirho.push(format!(
            "cairn-source-dictionary-test-{}-{}-chirho",
            std::process::id(),
            suffix_chirho
        ));
        let _ = std::fs::remove_dir_all(&path_chirho);
        std::fs::create_dir_all(path_chirho.join("content_chirho")).unwrap();
        path_chirho
    }

    fn valid_spec_chirho() -> SourceDictionarySpecChirho {
        SourceDictionarySpecChirho {
            dictionary_path_chirho: PathBuf::from("content_chirho/home_copy_chirho.json"),
            value_type_chirho: "crate::content_chirho::HomeCopyChirho".to_string(),
            const_name_chirho: "HOME_COPY_JSON_CHIRHO".to_string(),
            function_name_chirho: "home_copy_chirho".to_string(),
        }
    }

    #[test]
    fn generates_typed_source_dictionary_constant_chirho() {
        let root_chirho = temp_root_chirho("happy");
        std::fs::write(
            root_chirho.join("content_chirho/home_copy_chirho.json"),
            "{\n  \"title_chirho\": \"Riverbend\"\n}\n",
        )
        .unwrap();
        let source_chirho =
            generate_source_dictionary_source_chirho(&root_chirho, &valid_spec_chirho()).unwrap();
        assert!(source_chirho.contains("pub const HOME_COPY_JSON_CHIRHO: &str"));
        assert!(source_chirho
            .contains("pub fn try_home_copy_chirho() -> Result<crate::content_chirho::HomeCopyChirho, serde_json::Error>"));
        assert!(source_chirho
            .contains("pub fn home_copy_chirho() -> crate::content_chirho::HomeCopyChirho"));
        assert!(source_chirho.contains("\"title_chirho\": \"Riverbend\""));
        let _ = std::fs::remove_dir_all(root_chirho);
    }

    #[test]
    fn rejects_dictionary_parent_escape_chirho() {
        let root_chirho = temp_root_chirho("parent");
        let mut spec_chirho = valid_spec_chirho();
        spec_chirho.dictionary_path_chirho = PathBuf::from("../outside_chirho.json");
        let error_chirho =
            generate_source_dictionary_source_chirho(&root_chirho, &spec_chirho).unwrap_err();
        assert!(error_chirho.contains("must not contain '..'"));
        let _ = std::fs::remove_dir_all(root_chirho);
    }

    #[test]
    fn rejects_non_object_dictionary_json_chirho() {
        let root_chirho = temp_root_chirho("scalar");
        std::fs::write(
            root_chirho.join("content_chirho/home_copy_chirho.json"),
            "\"not an object\"",
        )
        .unwrap();
        let error_chirho =
            generate_source_dictionary_source_chirho(&root_chirho, &valid_spec_chirho())
                .unwrap_err();
        assert!(error_chirho.contains("must be an object"));
        let _ = std::fs::remove_dir_all(root_chirho);
    }

    #[test]
    fn rejects_bad_const_name_chirho() {
        let root_chirho = temp_root_chirho("bad-const");
        std::fs::write(
            root_chirho.join("content_chirho/home_copy_chirho.json"),
            "{\"title_chirho\":\"Riverbend\"}",
        )
        .unwrap();
        let mut spec_chirho = valid_spec_chirho();
        spec_chirho.const_name_chirho = "HomeCopyChirho".to_string();
        let error_chirho =
            generate_source_dictionary_source_chirho(&root_chirho, &spec_chirho).unwrap_err();
        assert!(error_chirho.contains("must end with _CHIRHO"));
        let _ = std::fs::remove_dir_all(root_chirho);
    }
}
